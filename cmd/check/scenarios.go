func checkReadApiaryStatus(c *client) error {
	if err := seedApiary(c, demoApiaryID, "北岭蜂场", "北岭片区", "周岚"); err != nil {
		return err
	}
	for _, hiveID := range []string{"hive-01", "hive-02", "hive-03"} {
		if err := seedHive(c, demoApiaryID, hiveID, "langstroth"); err != nil {
			return err
		}
	}
	if _, err := c.expect("POST", "/hives/hive-02/state", map[string]any{"target": "production"}, 200,
		`"to":"production"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/inspections", map[string]any{
		"observedAt": "2026-04-10T09:00:00Z", "colonyStrength": 4, "broodPattern": "solid",
		"temper": "calm", "miteCount": 12, "note": "",
	}, 201, `"mite_load"`); err != nil {
		return err
	}
	report, err := c.expect("GET", "/apiaries/apiary-north/status?asOf=2026-04-12T00:00:00Z", nil, 200,
		`"hiveCount":3`, `"colonized":2`, `"production":1`, `"layingQueens":0`)
	if err != nil {
		return err
	}
	for _, fragment := range []string{
		`"needsInspection":["hive-02","hive-03"]`,
		`"concernHives":["hive-01"]`,
	} {
		if !strings.Contains(report.text(), fragment) {
			return fmt.Errorf("状态汇总缺少 %q：%s", fragment, report.text())
		}
	}
	if err := report.mustOrder(`"hiveId":"hive-01"`, `"hiveId":"hive-02"`); err != nil {
		return err
	}
	if _, err := c.expect("GET", "/apiaries/apiary-missing/status", nil, 404, `"code":"not_found"`); err != nil {
		return err
	}
	if _, err := c.expect("GET", "/apiaries/apiary-north/status?asOf=not-a-time", nil, 400,
		`"code":"invalid_request"`); err != nil {
		return err
	}
	return nil
}

// checkAuditEvents 校验审计事件与业务结果同源：被采纳的写入按序留下事件，
// 失败或被拒绝的请求不留事件，重复读取同一范围得到稳定内容。
func checkAuditEvents(c *client) error {
	if err := seedDefault(c); err != nil {
		return err
	}
	// 编号冲突与越界量测均被拒绝，不得留下事件。
	if _, err := c.expect("POST", "/apiaries", map[string]any{
		"id": "apiary-north", "name": "重复蜂场", "district": "北岭片区", "keeper": "周岚",
	}, 409, `"code":"conflict"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/apiaries/apiary-north/hives", map[string]any{
		"id": "hive-01", "model": "warre",
	}, 409, `"code":"conflict"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/inspections", map[string]any{
		"observedAt": "2026-04-10T09:00:00Z", "colonyStrength": 3, "broodPattern": "patchy",
		"temper": "aggressive", "miteCount": 12, "note": "西侧巢门观察",
	}, 201, `"inspection-000001"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/inspections", map[string]any{
		"observedAt": "2026-04-10T10:00:00Z", "colonyStrength": 9, "broodPattern": "solid",
		"temper": "calm", "miteCount": 1, "note": "",
	}, 400, `"code":"invalid_request"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/queens", map[string]any{
		"origin": "bred", "introducedAt": "2026-04-02T08:00:00Z", "reason": "aging",
	}, 201, `"queen-000001"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/state", map[string]any{"target": "production"}, 200,
		`"to":"production"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/state", map[string]any{"target": "production"}, 409,
		`"code":"invalid_state"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/queens", map[string]any{
		"origin": "cells", "introducedAt": "2026-04-20T08:00:00Z", "reason": "aggression",
	}, 201, `"queen-000002"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/state", map[string]any{"target": "retired"}, 200,
		`"to":"retired"`); err != nil {
		return err
	}
	// 已退役蜂箱的巡检与换王被拒绝，不得留下事件。
	if _, err := c.expect("POST", "/hives/hive-01/inspections", map[string]any{
		"observedAt": "2026-04-11T09:00:00Z", "colonyStrength": 3, "broodPattern": "solid",
		"temper": "calm", "miteCount": 1, "note": "",
	}, 409, `"code":"invalid_state"`); err != nil {
		return err
	}
	if _, err := c.expect("POST", "/hives/hive-01/queens", map[string]any{
		"origin": "bred", "introducedAt": "2026-05-02T08:00:00Z", "reason": "loss",
	}, 409, `"code":"invalid_state"`); err != nil {
		return err
	}

	// 蜂场范围：七条被采纳的写入各留一条事件，顺序稳定，事实与结果同源。
	first, err := c.expect("GET", "/apiaries/apiary-north/events", nil, 200,
		`"seq":1`, `"type":"apiary_registered"`, `"name":"北岭蜂场"`,
		`"type":"hive_installed"`, `"model":"langstroth"`, `"state":"colonized"`,
		`"type":"inspection_recorded"`, `"inspectionId":"inspection-000001"`,
		`"concerns":["mite_load","temper_risk"]`,
		`"type":"queen_replaced"`, `"queenId":"queen-000001"`, `"markColor":"white"`,
		`"queenId":"queen-000002"`, `"closedQueenId":"queen-000001"`, `"closedState":"superseded"`,
		`"type":"hive_state_advanced"`, `"from":"colonized"`, `"to":"production"`, `"to":"retired"`)
	if err != nil {
		return err
	}
	if count := strings.Count(first.text(), `"seq":`); count != 7 {
		return fmt.Errorf("蜂场事件数应为 7，实际 %d：%s", count, first.text())
	}
	for _, pair := range [][2]string{
		{`"type":"apiary_registered"`, `"type":"hive_installed"`},
		{`"type":"hive_installed"`, `"type":"inspection_recorded"`},
		{`"type":"inspection_recorded"`, `"type":"queen_replaced"`},
		{`"queenId":"queen-000001"`, `"queenId":"queen-000002"`},
		{`"to":"production"`, `"to":"retired"`},
	} {
		if err := first.mustOrder(pair[0], pair[1]); err != nil {
			return err
		}
	}
	// 重复读取同一范围，内容完全一致。
	again, err := c.expect("GET", "/apiaries/apiary-north/events", nil, 200)
	if err != nil {
		return err
	}
	if again.text() != first.text() {
		return fmt.Errorf("重复读取蜂场事件结果不一致：%s 与 %s", first.text(), again.text())
	}

	// 蜂箱范围：不含蜂场录入事件；被拒绝的请求没有留下对应事实。
	hiveEvents, err := c.expect("GET", "/hives/hive-01/events", nil, 200,
		`"type":"hive_installed"`, `"inspectionId":"inspection-000001"`, `"queenId":"queen-000002"`)
	if err != nil {
		return err
	}
	if strings.Contains(hiveEvents.text(), `"type":"apiary_registered"`) {
		return fmt.Errorf("蜂箱事件不应包含蜂场录入事件：%s", hiveEvents.text())
	}
	if strings.Contains(hiveEvents.text(), "inspection-000002") {
		return fmt.Errorf("被拒绝的巡检不应留下事件：%s", hiveEvents.text())
	}
	for eventType, want := range map[string]int{
		`"type":"inspection_recorded"`: 1,
		`"type":"queen_replaced"`:      2,
		`"type":"hive_state_advanced"`: 2,
		`"type":"hive_installed"`:      1,
	} {
		if count := strings.Count(hiveEvents.text(), eventType); count != want {
			return fmt.Errorf("蜂箱事件中 %s 应出现 %d 次，实际 %d 次：%s", eventType, want, count, hiveEvents.text())
		}
	}
	if count := strings.Count(hiveEvents.text(), `"seq":`); count != 6 {
		return fmt.Errorf("蜂箱事件数应为 6，实际 %d：%s", count, hiveEvents.text())
	}
	hiveAgain, err := c.expect("GET", "/hives/hive-01/events", nil, 200)
	if err != nil {
		return err
	}
	if hiveAgain.text() != hiveEvents.text() {
		return fmt.Errorf("重复读取蜂箱事件结果不一致：%s 与 %s", hiveEvents.text(), hiveAgain.text())
	}

	if _, err := c.expect("GET", "/apiaries/apiary-missing/events", nil, 404, `"code":"not_found"`); err != nil {
		return err
	}
	if _, err := c.expect("GET", "/hives/hive-missing/events", nil, 404, `"code":"not_found"`); err != nil {
		return err
	}
	return nil
}
